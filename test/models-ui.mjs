import { _electron as electron } from 'playwright';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';

const home = fs.mkdtempSync(path.join(os.tmpdir(), 'proteus-models-ui-'));
let app;
try {
  app = await electron.launch({ args: ['.', '--user-data-dir=' + path.join(home, 'electron')], env: { ...process.env, PROTEUS_HOME: home, PORT: '0' }, timeout: 60000 });
  const page = await app.firstWindow();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const controls = { reasoningEfforts: ['none', 'high', 'future'], contextTiers: [{id:'default',promptTokens:272000},{id:'long_context',promptTokens:872000}], maxOutputTokens:128000 };
  let models = [{ id: 'synthetic-one', name: 'Synthetic One', controls }, { id: 'synthetic-two', name: 'Synthetic Two', controls }];
  const catalog = () => ({ available:true, models, checkedAt:new Date().toISOString(), refreshIntervalMs:300000 });
  await page.route('**/api/state', async route => { const response = await route.fetch(); const value = await response.json(); value.providerStatus = catalog(); value.providerStatuses = {copilot:catalog(),codex:{...catalog(),models:[{id:"codex-fixture",name:"Codex fixture",controls:{...controls,serviceTiers:[{id:"fast",name:"Fast"}]}}]}}; await route.fulfill({json:value}); });
  await page.route('**/api/provider', route => route.fulfill({ json: route.request().postDataJSON().provider === 'codex' ? {...catalog(),models:[{id:'codex-fixture',name:'Codex fixture',controls:{...controls,serviceTiers:[{id:'fast',name:'Fast'}]}}]} : catalog() }));
  await page.getByRole('heading', { name: 'Work that keeps moving.' }).waitFor();
  await page.locator('[data-schedule]').first().click();
  await page.locator('#provider').selectOption('copilot');
  await page.locator('#model option[value="synthetic-two"]').waitFor({ state: 'attached' });
  await page.locator('#model').selectOption('synthetic-two');
  await page.locator('#model-effort').selectOption('none');
  await page.locator('#model-context').selectOption('long_context');
  await page.locator('#save').click();
  await page.getByText('Schedule saved.', { exact: true }).waitFor();
  assert.equal(await page.locator('#model').inputValue(), 'synthetic-two');
  assert.equal(await page.locator('#model-effort').inputValue(), 'none');
  assert.equal(await page.locator('#model-context').inputValue(), 'long_context');
  const scheduleFile = path.join(home, 'schedules', fs.readdirSync(path.join(home,'schedules'))[0]);
  const saved = JSON.parse(fs.readFileSync(scheduleFile));
  assert.equal(saved.reasoningEffort,'none'); assert.equal(saved.contextTier,'long_context');
  await page.locator('[data-close]').first().click();
  fs.writeFileSync(scheduleFile,JSON.stringify({...saved,name:'AI renamed schedule',reasoningEffort:'future'}));
  await page.locator('[data-schedule]').first().click();
  assert.equal(await page.locator('#name').inputValue(),'AI renamed schedule');
  assert.equal(await page.locator('#model-effort').inputValue(),'future');
  await page.locator('#name').fill('Unsaved app edit');
  fs.writeFileSync(scheduleFile,JSON.stringify({...saved,name:'Second AI edit',reasoningEffort:'high'}));
  await page.locator('#save').click();
  await page.getByText('This file changed outside the app. Reload before saving.', {exact:true}).waitFor();
  assert.equal(await page.locator('#name').inputValue(),'Unsaved app edit');
  await page.locator('#reload').click();
  await page.locator('#name').filter({visible:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('#name')?.value==='Second AI edit');
  assert.equal(await page.locator('#model-effort').inputValue(),'high');
  models = [{ id: 'synthetic-one', name: 'Synthetic One', controls }];
  await page.locator('#model-refresh').click();
  await page.locator('#model option[value="synthetic-two"]').filter({ hasText: 'unavailable' }).waitFor({ state: 'attached' });
  assert.equal(await page.locator('#model').inputValue(), 'synthetic-two', 'Refresh preserves an unavailable saved model');
  await page.locator('[data-page="settings"]').click();
  await page.locator('#settings-provider').selectOption('copilot');
  await page.locator('#settings-model-refresh').click();
  await page.locator('#settings-model option[value="synthetic-one"]').waitFor({ state: 'attached' });
  assert.equal(await page.locator('#settings-model').evaluate(e => e.tagName), 'SELECT');
  await page.locator('#new-chat').click();
  await page.locator('#chat-provider').selectOption('copilot');
  await page.locator('#chat-model').selectOption('synthetic-one');
  await page.locator('#chat-model-effort').selectOption('none');
  await page.locator('#chat-model-context').selectOption('long_context');
  assert.match(await page.locator('#chat-model-context option:checked').textContent(),/872K/);
  await page.locator('#chat-provider').selectOption('codex');
  await page.locator('#chat-model').selectOption('codex-fixture');
  assert.equal(await page.locator('#chat-model-effort').inputValue(),'');
  await page.locator('#chat-model-speed').selectOption('fast');
  assert.equal(await page.locator('#chat-model option[value="synthetic-one"]').count(),0);
  await page.screenshot({path:'/private/tmp/proteus-model-settings-mac.png'});
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, checks: ['catalog selection persists', 'missing saved model retained', 'settings and chat share capabilities', 'effort and context persist', 'external reload and conflict protection'] }));
} finally { if (app) await app.close(); fs.rmSync(home, { recursive: true, force: true }); }
